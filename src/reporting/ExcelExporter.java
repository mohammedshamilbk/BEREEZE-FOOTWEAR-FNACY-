    /**
     * Export InventoryReport to Excel with custom filename
     */
    public synchronized File exportInventoryReport(InventoryReport report, String filename) throws IOException {
        Map<String, Object> data = report.getReportData();
        File outputFile = createOutputFile(filename, ".xlsx");
        
        try (FileOutputStream fos = new FileOutputStream(outputFile)) {
            StringBuilder content = new StringBuilder();
            
            // Header
            content.append(report.getReportTitle()).append("\n");
            content.append("Generated on: ").append(report.getReportDate()).append("\n");
            content.append("Generated by: ").append(report.getGeneratedBy()).append("\n\n");
            
            // Inventory Summary
            content.append("INVENTORY SUMMARY\n");
            content.append("Current Stock Value,").append(data.get("currentStockValue")).append("\n");
            content.append("Total Items in Stock,").append(data.get("totalItemsInStock")).append("\n");
            content.append("Dead Stock Count,").append(data.get("deadStockCount")).append("\n");
            content.append("Dead Stock Value,").append(data.get("deadStockValue")).append("\n");
            content.append("Fast Moving Count,").append(data.get("fastMovingCount")).append("\n");
            content.append("Fast Moving Value,").append(data.get("fastMovingValue")).append("\n\n");
            
            // Low Stock Items
            content.append("LOW STOCK ITEMS\n");
            content.append("Item Code,Item Name,Current Stock,Minimum Stock,Category\n");
            List<InventoryReport.LowStockItem> lowStockItems = 
                (List<InventoryReport.LowStockItem>) data.get("lowStockItems");
            lowStockItems.forEach(item ->
                content.append(item.itemCode).append(",")
                       .append(item.itemName).append(",")
                       .append(item.currentStock).append(",")
                       .append(item.minimumStock).append(",")
                       .append(item.category).append("\n")
            );
            content.append("\n");
            
            // Category Wise Inventory
            content.append("CATEGORY WISE INVENTORY\n");
            content.append("Category,Total Quantity,Total Value,Inward,Outward\n");
            Map<String, InventoryReport.StockMovement> categoryInventory = 
                (Map<String, InventoryReport.StockMovement>) data.get("categoryWiseInventory");
            categoryInventory.forEach((cat, movement) ->
                content.append(cat).append(",")
                       .append(movement.totalQuantity).append(",")
                       .append(movement.totalValue).append(",")
                       .append(movement.inwardQuantity).append(",")
                       .append(movement.outwardQuantity).append("\n")
            );
            
            fos.write(content.toString().getBytes());
        }
        
        return outputFile;
    }
    
